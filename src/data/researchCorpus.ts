/**
 * Builds the public corpus, deriving each row's verification state from the
 * real extraction rules instead of a hand-written label.
 */
function buildCorpus(): ResearchResult[] {
  return seeds.map((seed) => {
    const contactEmail = seed.contactEmail || seed.email
    const verification = verifyContactExtraction({
      website: seed.website,
      email: contactEmail,
      phone: seed.phone,
    })

    const reputation: ReputationTier = (() => {
      if (seed.establishedYear === null) return 'Emerging'
      if (seed.establishedYear <= 1990) return 'Established'
      if (seed.establishedYear <= 2005) return 'Reputed'
      return 'Emerging'
    })()

    return {
      id: `res-${seed.key}`,
      name: seed.name,
      type: seed.type,
      state: seed.state,
      district: seed.district,
      city: seed.city,
      address: seed.address,
      medium: seed.medium,
      studentCount: seed.studentCount,
      establishedYear: seed.establishedYear,
      reputation,
      website: seed.website,
      sourceUrl: `${seed.website.replace(/\/$/, '')}${seed.path}`,
      extractionMethod: seed.method,
      email: seed.email,
      phone: seed.phone,
      contactName: seed.contactName,
      contactDesignation: seed.contactDesignation,
      contactEmail,
      source: seed.source,
      verification: verification.status,
      extractionNotes: verification.notes,
      selected: false,
    }
  })
}

export const researchCorpus: ResearchResult[] = buildCorpus()

/** Counts of each verification state, used by the results header. */
export function corpusSummary(list: ResearchResult[]) {
  return {
    verified: list.filter((item) => item.verification === 'verified').length,
    partial: list.filter((item) => item.verification === 'needs-review').length,
    unverified: list.filter((item) => item.verification === 'unverified').length,
  }
}

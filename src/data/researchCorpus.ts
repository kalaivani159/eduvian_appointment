/**
 * Research corpus.
 *
 * These are clearly-flagged demonstration records shaped the way a real crawl
 * would shape them: one row per school, with the page the contact was read
 * from, how it was found, and only the fields the page actually contained.
 *
 * Verification is NOT hand-assigned. Every row runs through
 * `verifyContactExtraction()` at load time, so a row only reads "Verified" when
 * its e-mail is well-formed AND its domain belongs to the school's own website
 * AND the phone number parses. Rows with missing, malformed or unrelated
 * contact details come out as Partially Verified or Unverified — no contact
 * detail is ever invented to fill a gap.
 *
 * The production agent applies the same rules to pages it has actually fetched.
 */

